// 第 n 关（从 0 数）。难度像过山车：第 1 关送分（5 格槽），之后难关 3 格槽、喝水关 4 格槽交替。
// 8 关以后循环，全部 3 格槽
function levelDef(n) {
  const base = LEVELS[n % LEVELS.length];
  if (n < LEVELS.length) return base;
  return Object.assign({}, base, { slots: Math.max(3, base.slots - 1) });
}

